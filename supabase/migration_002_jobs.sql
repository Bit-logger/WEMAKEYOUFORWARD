-- 1) Jobs (employer listings + the sample job board used for job search)
create table if not exists public.jobs (
  id bigint generated by default as identity (start with 5000) primary key,
  employer_id bigint references public.employers(id) on delete cascade,  -- null = sample job
  is_demo boolean not null default false,                                 -- true = sample / test job
  title text not null,
  company text not null,
  company_initials text not null default '',
  company_color text not null default '#5D4FE0',
  location text not null default '',
  type text not null default 'Full-time',
  mode text not null default 'On-site',
  experience text not null default 'Entry level',
  industry text not null default 'Technology',
  salary_min integer not null default 0,
  salary_max integer not null default 0,
  tags jsonb not null default '[]'::jsonb,
  closing_date date,
  featured boolean not null default false,
  urgent boolean not null default false,
  status text not null default 'Draft'
    check (status in ('Draft','Pending','Approved','Rejected','Review','Suspended','Paused','Closed')),
  views integer not null default 0,
  about_role text not null default '',
  responsibilities jsonb not null default '[]'::jsonb,
  requirements jsonb not null default '[]'::jsonb,
  benefits jsonb not null default '[]'::jsonb,
  about_company text not null default '',
  package text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists jobs_status_idx on public.jobs(status);
create index if not exists jobs_employer_idx on public.jobs(employer_id);

-- 2) Employer pipeline stage on each application (New -> Shortlisted -> Interview -> Hired)
alter table public.applications add column if not exists stage text not null default 'New';
create index if not exists applications_job_idx on public.applications(job_id);

-- 3) Paid job postings (checkout)
create table if not exists public.job_orders (
  id bigint generated by default as identity primary key,
  employer_id bigint not null references public.employers(id) on delete cascade,
  job_id bigint references public.jobs(id) on delete set null,
  package text not null,
  amount numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);

-- 4) Admin moderation reports
create table if not exists public.admin_reports (
  id bigint generated by default as identity primary key,
  type text not null,
  reason text not null default '',
  target text not null default '',
  status text not null default 'Open' check (status in ('Open','Resolved')),
  created_at timestamptz not null default now()
);

-- Tables are accessed only by the Flask server (service-role key). Keep RLS on with no public policies
-- so the browser/anon key can never read or write them directly.
alter table public.jobs enable row level security;
alter table public.job_orders enable row level security;
alter table public.admin_reports enable row level security;

