create table if not exists public.employers (
 id bigint generated by default as identity primary key,
 email text not null unique,
 password_hash text,
 google_sub text unique,
 onboarding_complete boolean not null default false,
 is_demo boolean not null default false,
 created_at timestamptz not null default now(),
 last_login_at timestamptz
);
create table if not exists public.companies (
 employer_id bigint primary key references public.employers(id) on delete cascade,
 name text not null,
 country text not null,
 registered_name text not null,
 is_registered boolean not null default true,
 abn text,
 contact_first text not null,
 contact_last text not null,
 phone_country text not null,
 phone text not null,
 updated_at timestamptz not null default now()
);
create table if not exists public.seekers (
 id bigint generated by default as identity primary key,
 email text not null unique,
 password_hash text,
 google_sub text unique,
 full_name text not null default '',
 plan text not null default 'free' check (plan in ('free','premium')),
 is_demo boolean not null default false,
 created_at timestamptz not null default now(),
 last_login_at timestamptz
);
create table if not exists public.seeker_profiles (
 seeker_id bigint primary key references public.seekers(id) on delete cascade,
 headline text not null default '', phone text not null default '', location text not null default '',
 education jsonb not null default '[]'::jsonb, experience jsonb not null default '[]'::jsonb,
 no_experience boolean not null default false, skills jsonb not null default '[]'::jsonb,
 interests jsonb not null default '[]'::jsonb, pref_job_type text not null default '',
 pref_work_mode text not null default '', pref_location text not null default '',
 work_rights text not null default '', linkedin text not null default '', portfolio text not null default '',
 updated_at timestamptz not null default now()
);
create table if not exists public.seeker_resumes (
 seeker_id bigint primary key references public.seekers(id) on delete cascade,
 template text not null default 'modern', summary text not null default '', updated_at timestamptz not null default now()
);
create table if not exists public.applications (
 id bigint generated by default as identity primary key,
 seeker_id bigint not null references public.seekers(id) on delete cascade,
 job_id bigint not null, status text not null default 'Applied', cover_note text not null default '',
 applied_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(seeker_id, job_id)
);
create table if not exists public.saved_jobs (
 seeker_id bigint not null references public.seekers(id) on delete cascade,
 job_id bigint not null, saved_at timestamptz not null default now(), primary key(seeker_id, job_id)
);
